export type Field = {
  key: string;
  label: string;
  type:
    'text' | 'email' | 'number' | 'date' | 'select' | 'relation' | 'textarea' | 'boolean' | 'json';
  required?: boolean;
  options?: string[];
  resource?: string;
  min?: number;
};
export type Resource = {
  model: string;
  label: string;
  group: string;
  fields: Field[];
  columns: string[];
  search: string[];
  unit?: boolean;
  site?: boolean;
  readonly?: boolean;
  dateField?: string;
  statusFilters?: string[];
};
const f = (
  key: string,
  label: string,
  type: Field['type'] = 'text',
  required = true,
  extra: Partial<Field> = {},
): Field => ({ key, label, type, required, ...extra });
const rel = (key: string, label: string, resource: string, required = true) =>
  f(key, label, 'relation', required, { resource });
const sel = (key: string, label: string, options: string[], required = true) =>
  f(key, label, 'select', required, { options });
const num = (key: string, label: string, required = true) =>
  f(key, label, 'number', required, { min: 0 });
const date = (key: string, label: string, required = true) => f(key, label, 'date', required);
const name = f('name', 'Name');
const unit = rel('businessUnitId', 'Business unit', 'business-units');
const site = rel('siteId', 'Site', 'sites');
const employee = (key: string, label: string, required = true) =>
  rel(key, label, 'employees', required);
const status = sel('status', 'Status', ['ACTIVE', 'INACTIVE']);
function r(
  model: string,
  label: string,
  group: string,
  fields: Field[],
  columns: string[],
  search = ['name'],
  extra: Partial<Resource> = {},
): Resource {
  return {
    model,
    label,
    group,
    fields,
    columns,
    search,
    unit: fields.some((f) => f.key === 'businessUnitId'),
    site: fields.some((f) => f.key === 'siteId'),
    ...extra,
  };
}
